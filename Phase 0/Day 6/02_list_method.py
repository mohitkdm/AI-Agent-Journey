# list Updating
number=[10,20,30,40,"Mohit","Nikhil"]
print(number)
number[0]=100
print(number)

# list append
number.append(21)
print(number)

# list insert
number.insert(5,2004)
print(number)

# list extend
number.extend(["yash",29,5,2010])
print(number)

# list element removing
number.remove(21)
print(number)

number.pop()
print(number)

number.pop(3)
print(number)

